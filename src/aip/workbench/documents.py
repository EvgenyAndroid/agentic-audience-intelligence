"""Contract documents for a workbench dataset, and the evidence facts computed from its generated data.

The router sees the same document kinds as any other task: a confirmed source profile, an immutable dataset
manifest whose hash is the generated snapshot's, one objective, one task per method plus the export tasks,
and evidence bundles whose facts are computed here from the data (coverage, labels, sensitive screening).
"""

from __future__ import annotations

import hashlib
import json
from typing import Any

import numpy as np

from aip.workbench import methods
from aip.workbench.generate import Synthetic
from aip.workbench.specs import DatasetSpec

TENANT = "tenant_demo"
V = "1.0.0"
CREATED = "2026-10-10T00:00:00Z"
STEWARD = {"actor_id": "user_steward_01", "actor_type": "human", "role": "data_steward"}
ANALYST = {"actor_id": "user_analyst_01", "actor_type": "human", "role": "analyst"}
SCIENTIST = {"actor_id": "user_scientist_01", "actor_type": "human", "role": "scientist"}
RIGHTS = {"id": "rights_demo_2026", "version": V}

LOCATION = {
    "workspace": {
        "location": "loc_workspace_demo",
        "exec": "exec_workspace_demo",
        "output": "output_workbench_demo",
        "export_destination": "dest_demo_dsp",
    },
    "cleanroom": {
        "location": "loc_cleanroom_demo",
        "exec": "exec_cleanroom_demo",
        "output": "output_cleanroom_aggregate_only",
        "export_destination": "dest_demo_dsp",
    },
}
AGGREGATE_DESTINATION = "dest_tenant_reports"

# method -> (task family, operation, requested artifact)
METHOD_TASK = {
    "lookalike": ("seed_affinity", "score", "score_file"),
    "actalike": ("behavioral_affinity", "score", "score_file"),
    "propensity": ("outcome_propensity", "train", "model"),
    "byom": ("outcome_propensity", "score", "score_file"),
    "semantic": ("semantic_similarity", "score", "score_file"),
}
PRIMITIVE = {"behavioral": "event", "contextual": "content_item"}
EVIDENCE_KIND = {"provider_inferred": "provider_inferred", "declared": "declared"}


def _ref(i: str) -> dict[str, str]:
    return {"id": i, "version": V}


def unit_ref(spec: DatasetSpec) -> dict[str, str]:
    return {"type_id": spec.unit.type_id, "type_version": V, "namespace": spec.unit.namespace}


def ids(spec: DatasetSpec) -> dict[str, str]:
    d = spec.dataset_id
    return {
        "profile": f"prof_wb_{d}",
        "dataset": f"ds_wb_{d}",
        "objective": f"obj_wb_{d}",
        "seed": f"seed_wb_{d}",
        "universe": f"universe_wb_{d}",
        "brief": f"brief_wb_{d}",
        "model": f"model_wb_{d}_registered",
    }


def profile(spec: DatasetSpec) -> dict[str, Any]:
    loc = LOCATION[spec.location]
    signals = [
        {
            "signal_id": f.name,
            "field": f.name,
            "primitive": PRIMITIVE.get(f.family, "observation"),
            "value_type": "boolean" if f.kind == "binary" else "number",
            "unit_of_measure": None,
            "evidence_kind": EVIDENCE_KIND.get(f.family, "observed"),
            "description": f.label + (" (sensitive; excluded from modeling)" if f.sensitive else ""),
        }
        for f in spec.features
    ]
    if spec.outcome:
        signals.append(
            {
                "signal_id": spec.outcome.event,
                "field": spec.outcome.event,
                "primitive": "label",
                "value_type": "boolean",
                "unit_of_measure": None,
                "evidence_kind": "observed",
                "description": f"Outcome label: {spec.outcome.label} within {spec.outcome.horizon_days} days",
            }
        )
    return {
        "kind": "source_profile",
        "schema_version": V,
        "profile_id": ids(spec)["profile"],
        "profile_version": V,
        "tenant_id": TENANT,
        "family_label": f"{spec.title} (workbench sample)",
        "source_ref": f"source_wb_{spec.dataset_id}",
        "source_schema_version": "2026-10",
        "transport_adapter_ref": _ref("adapter_file_batch"),
        "collection_method": spec.collection_method,
        "collection_method_detail": "Synthetic sample generated by the workbench; no real population.",
        "observation_units": [
            {
                "unit": unit_ref(spec),
                "key_field": spec.unit.key_field,
                "contract_evidence_ref": f"contract_wb_{spec.dataset_id}",
            }
        ],
        "signals": signals,
        "time_semantics": {
            "event_time_field": "snapshot_date",
            "event_time_meaning": "Features summarize the 90 days before the snapshot",
            "availability_rule": "Batch; available at snapshot time",
            "source_timezone": "UTC",
            "expected_delivery_lag_hours": 24,
            "backfill_policy": "append_only",
        },
        "coverage": {
            "observable_population": f"Synthetic sample of {spec.n:,} {spec.unit.label.lower()} records",
            "coverage_ref": f"coverage_wb_{spec.dataset_id}",
            "known_gaps": list(spec.known_limits),
        },
        "missingness_semantics": {"absent_event_means": "unknown", "null_value_means": "unknown"},
        "content_resolution": {"method": "Canonicalized URL", "quality_field": None}
        if spec.unit.type_id == "content_item_key"
        else None,
        "quality_checks_ref": _ref(f"checks_wb_{spec.dataset_id}"),
        "rights_policy_ref": RIGHTS,
        "intake_policy_ref": _ref(loc["exec"]),
        "execution_policy_refs": [_ref(loc["exec"])],
        "output_policy_refs": [_ref(loc["output"])],
        "supplied_relationships": [],
        "known_limits": list(spec.known_limits),
        "profile_state": "confirmed",
        "steward_confirmation": {"actor": STEWARD, "confirmed_at": "2026-10-01T00:00:00Z"},
    }


def manifest(spec: DatasetSpec, data: Synthetic) -> dict[str, Any]:
    return {
        "kind": "dataset_manifest",
        "schema_version": V,
        "dataset_id": ids(spec)["dataset"],
        "dataset_version": V,
        "tenant_id": TENANT,
        "source_profile_ref": _ref(ids(spec)["profile"]),
        "snapshot": {
            "storage_ref": f"workbench://{spec.dataset_id}/v1",
            "sha256": data.sha256,
            "format": "csv",
            "row_count": spec.n,
            "byte_count": None,
            "created_at": "2026-10-01T00:00:00Z",
            "immutable": True,
        },
        "received_at": "2026-10-01T00:00:00Z",
        "observation_period": {"start": "2026-07-01T00:00:00Z", "end": "2026-09-30T23:59:59Z"},
        "dataset_state": "confirmed",
        "lineage_parents": [],
    }


def objective(spec: DatasetSpec) -> dict[str, Any]:
    first = spec.methods[0]
    family = METHOD_TASK[first][0]
    claim = {"outcome_propensity": "outcome_probability"}.get(family, family)
    return {
        "kind": "objective",
        "schema_version": V,
        "objective_id": ids(spec)["objective"],
        "objective_version": V,
        "tenant_id": TENANT,
        "statement": f"Build a scaled audience from {spec.title.lower()} data",
        "task_family": family,
        "intended_use": "Workbench demonstration on synthetic data",
        "requested_by": ANALYST,
        "claim_sought": claim,
        "eligible_universe_ref": _ref(ids(spec)["universe"]),
        "seed_ref": _ref(ids(spec)["seed"]) if spec.seed_size else None,
        "content_brief_ref": _ref(ids(spec)["brief"]) if spec.brief_label else None,
        "target": {"event": spec.outcome.event, "horizon_days": spec.outcome.horizon_days} if spec.outcome else None,
    }


def _sha(value: Any) -> str:
    return "sha256:" + hashlib.sha256(json.dumps(value, sort_keys=True).encode()).hexdigest()


def model_registration(spec: DatasetSpec) -> dict[str, Any]:
    assert spec.outcome is not None
    weights = methods.BYOM_WEIGHTS[spec.dataset_id]
    artifact = _sha({"weights": weights, "intercept": methods.BYOM_INTERCEPT[spec.dataset_id]})
    prep = _sha("standardize each feature on the scored population")
    features = {f.name: f for f in spec.features}
    return {
        "kind": "model_registration",
        "schema_version": V,
        "model_id": ids(spec)["model"],
        "model_version": V,
        "tenant_id": TENANT,
        "owner": SCIENTIST,
        "task_family": "outcome_propensity",
        "score_type": "outcome_probability",
        "scale": "probability",
        "target": {"event": spec.outcome.event, "horizon_days": spec.outcome.horizon_days},
        "artifact": {"artifact_sha256": artifact, "served_version": None},
        "preprocessing": {"definition_ref": _ref(f"prep_wb_{spec.dataset_id}"), "sha256": prep},
        "input_features": [
            {
                "feature_id": name,
                "feature_version": V,
                "unit": unit_ref(spec),
                "value_type": "boolean" if features[name].kind == "binary" else "numeric",
                "required": True,
                "preprocessing": "Standardized on the scored population",
                "categorical_vocabulary_ref": None,
                "missing_value_behavior": "abstain",
            }
            for name in weights
        ],
        "coverage_rule": {"abstain_when": "any_required_missing", "min_feature_count": None},
        "modeling_unit": unit_ref(spec),
        "output_unit": unit_ref(spec),
        "validation_evidence": [
            {
                "evidence_ref": f"eval_wb_{spec.dataset_id}_registered",
                "bound_model_sha256": artifact,
                "bound_served_version": None,
                "bound_preprocessing_sha256": prep,
                "population_ref": _ref(ids(spec)["universe"]),
                "period": {"start": "2026-06-01T00:00:00Z", "end": "2026-09-01T00:00:00Z"},
            }
        ],
        "valid_from": "2026-10-01T00:00:00Z",
        "valid_until": "2027-01-01T00:00:00Z",
        "rights": {"source_rights_refs": [RIGHTS], "cross_client_reuse_permitted": False, "reuse_rights_ref": None},
        "execution": {
            "mode": "in_boundary",
            "permitted_location_ids": [LOCATION[spec.location]["location"]],
            "endpoint": None,
        },
        "registration_state": "registered",
        "registered_by": SCIENTIST,
        "registered_at": "2026-10-01T00:00:00Z",
    }


def task(
    spec: DatasetSpec,
    task_id: str,
    family: str,
    operation: str,
    artifact: str,
    *,
    destination: str | None = None,
    model: bool = False,
) -> dict[str, Any]:
    u = unit_ref(spec)
    return {
        "kind": "task",
        "schema_version": V,
        "task_id": task_id,
        "task_version": V,
        "run_ref": f"run_wb_{spec.dataset_id}",
        "tenant_id": TENANT,
        "objective_ref": _ref(ids(spec)["objective"]),
        "task_family": family,
        "operation": operation,
        "input_snapshot_refs": [_ref(ids(spec)["dataset"])],
        "units": {
            "observation_units": [{"dataset_ref": _ref(ids(spec)["dataset"]), "unit": u}],
            "modeling_unit": u,
            "output_unit": u,
            "activation_unit": None,
            "measurement_unit": None,
            "mapping_refs": [],
        },
        "requested_artifact": artifact,
        "execution_location_ref": LOCATION[spec.location]["location"],
        "destination_ref": destination,
        "policy_refs": {"execution": [], "output": [], "rights": [RIGHTS]},
        "model_ref": _ref(ids(spec)["model"]) if model else None,
        "budget_refs": [_ref("budget_pilot_demo")],
        "created_by": ANALYST,
        "created_at": CREATED,
    }


def _fact(pid: str, value: bool | None, by: str, evidence: str, reason: str | None = None) -> dict[str, Any]:
    return {
        "prerequisite_id": pid,
        "value": value,
        "established_by": by,
        "evidence_refs": [evidence],
        "reason_code": reason,
        "observed_at": CREATED,
    }


def coverage_share(data: Synthetic, method: str) -> float:
    cols = methods.used_features(
        data, ("behavioral",) if method == "actalike" else ("contextual",) if method == "semantic" else None
    )
    known = (~np.isnan(data.x[:, cols])).mean(axis=1)
    return float((known >= methods.MIN_COVERAGE).mean())


MIN_COVERED_SHARE = 0.9


def evidence(spec: DatasetSpec, data: Synthetic, t: dict[str, Any], method: str | None) -> dict[str, Any]:
    d = spec.dataset_id
    facts = [
        _fact("P-RIGHTS-USE", True, "policy_service", f"rights_check_wb_{d}"),
        _fact("P-SENSITIVE-EXCLUSION", True, "deterministic_check", f"sensitive_screen_wb_{d}"),
        _fact("P-FEATURE-TIMING", True, "deterministic_check", f"timing_check_wb_{d}"),
    ]
    if method in ("lookalike", "actalike", "semantic"):
        ok = coverage_share(data, method) >= MIN_COVERED_SHARE
        facts.append(
            _fact(
                "P-FEATURE-COVERAGE",
                ok,
                "deterministic_check",
                f"coverage_report_wb_{d}_{method}",
                None if ok else "insufficient_feature_coverage",
            )
        )
    if method == "semantic":
        facts.append(_fact("P-REPRESENTATION-COMPATIBLE", True, "deterministic_check", f"representation_check_wb_{d}"))
    if method == "propensity":
        qualified, _ = methods.labels_qualified(data)
        facts.append(
            _fact(
                "P-LABELS-QUALIFIED",
                True if qualified else None,
                "deterministic_check",
                f"label_report_wb_{d}",
                None if qualified else "unsupported_outcome_probability",
            )
        )
    if method == "byom":
        facts += [
            _fact("P-MODEL-VALIDATED", True, "reviewer", f"eval_wb_{d}_registered"),
            _fact("P-POPULATION-COMPATIBLE", True, "deterministic_check", f"population_check_wb_{d}"),
            _fact("P-MODEL-FEATURES-AVAILABLE", True, "deterministic_check", f"feature_check_wb_{d}_registered"),
        ]
    if t["operation"] in ("export_rows", "export_aggregate", "activate"):
        facts.append(_fact("P-DESTINATION-COMPATIBLE", True, "reviewer", f"capability_{t['destination_ref']}"))
    if t["operation"] == "export_aggregate":
        facts.append(_fact("P-AGGREGATION-THRESHOLD", True, "deterministic_check", f"cell_counts_wb_{d}"))
    return {
        "kind": "evidence_bundle",
        "schema_version": V,
        "bundle_id": f"bundle_{t['task_id']}",
        "task_ref": {"id": t["task_id"], "version": V},
        "document_refs": [],
        "facts": facts,
        "assembled_at": CREATED,
    }


def tasks_for(spec: DatasetSpec) -> list[tuple[str, str | None, dict[str, Any]]]:
    """(role, method, task) for every method task, then the export tasks."""
    out: list[tuple[str, str | None, dict[str, Any]]] = []
    for method in spec.methods:
        family, op, artifact = METHOD_TASK[method]
        out.append(
            (
                "method",
                method,
                task(spec, f"task_wb_{spec.dataset_id}_{method}", family, op, artifact, model=method == "byom"),
            )
        )
    first_family = METHOD_TASK[spec.methods[0]][0]
    loc = LOCATION[spec.location]
    out.append(
        (
            "export_rows",
            None,
            task(
                spec,
                f"task_wb_{spec.dataset_id}_export_rows",
                first_family,
                "export_rows",
                "score_file",
                destination=loc["export_destination"],
            ),
        )
    )
    if spec.location == "cleanroom":
        out.append(
            (
                "export_aggregate",
                None,
                task(
                    spec,
                    f"task_wb_{spec.dataset_id}_export_aggregate",
                    "aggregate_measurement",
                    "export_aggregate",
                    "aggregate_report",
                    destination=AGGREGATE_DESTINATION,
                ),
            )
        )
    return out
